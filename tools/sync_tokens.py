"""Copy the :root block of theme.css (the Streamlit app's palette) into
web/src/tokens.css so the web workspace uses the same colours.

    python tools/sync_tokens.py          write web/src/tokens.css
    python tools/sync_tokens.py --check  exit 1 if it is out of date
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / "theme.css"
TOKENS = ROOT / "web" / "src" / "tokens.css"
HEADER = ("/* GENERATED by tools/sync_tokens.py from theme.css :root - do not "
          "edit.\n   Run `python tools/sync_tokens.py` after changing theme.css. */\n")


def root_block(css):
    start = css.index(":root")
    return css[start:css.index("}", start) + 1] + "\n"


def expected():
    return HEADER + root_block(THEME.read_text())


def main(argv):
    want = expected()
    if "--check" in argv:
        if not TOKENS.exists() or TOKENS.read_text() != want:
            print("web/src/tokens.css is out of date: run "
                  "python tools/sync_tokens.py", file=sys.stderr)
            return 1
        print("tokens.css is in sync with theme.css")
        return 0
    TOKENS.write_text(want)
    print(f"wrote {TOKENS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
