def _bus(types, V, Pd, Qd, Pg=None, Bs=None):
    n = len(types)
    return pd.DataFrame({"Type": types, "V": V, "Pg": Pg or [0.0] * n, "Qg": [0.0] * n,
                         "Pd": Pd, "Qd": Qd, "Bs": Bs or [0.0] * n})


def _lines(rows):
    r = pd.DataFrame(rows, columns=["From", "To", "R", "X", "B", "Tap"])
    return r


